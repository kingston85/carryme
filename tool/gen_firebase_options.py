#!/usr/bin/env python3
"""Turns Firebase's google-services.json into lib/firebase_options.dart.

Usage:
    python3 tool/gen_firebase_options.py google-services.json

The GitHub build runs this automatically from the GOOGLE_SERVICES_JSON secret.
"""
import json
import pathlib
import sys

PACKAGE = "lr.carryme.carryme"
OUT = pathlib.Path("lib/firebase_options.dart")


def dart_str(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 1
    try:
        data = json.loads(pathlib.Path(sys.argv[1]).read_text(encoding="utf-8"))
    except Exception as exc:  # noqa: BLE001
        print(f"Could not read google-services.json: {exc}")
        print("Paste the WHOLE file (starting with { and ending with }) into the secret.")
        return 1

    info = data.get("project_info", {})
    clients = data.get("client", [])
    client = next(
        (c for c in clients
         if c.get("client_info", {}).get("android_client_info", {}).get("package_name") == PACKAGE),
        None,
    )
    if client is None:
        names = [c.get("client_info", {}).get("android_client_info", {}).get("package_name") for c in clients]
        print(f"No Android app with package name {PACKAGE} in google-services.json (found: {names}).")
        print("In the Firebase console, add an Android app with exactly that package name.")
        return 1

    api_keys = client.get("api_key", [])
    options = {
        "apiKey": api_keys[0]["current_key"] if api_keys else "",
        "appId": client["client_info"]["mobilesdk_app_id"],
        "messagingSenderId": info.get("project_number", ""),
        "projectId": info.get("project_id", ""),
        "storageBucket": info.get("storage_bucket", ""),
    }
    missing = [k for k, v in options.items() if not v and k != "storageBucket"]
    if missing:
        print(f"google-services.json is missing: {missing}")
        return 1

    fields = "\n".join(f"    {k}: {dart_str(v)}," for k, v in options.items() if v)
    OUT.write_text(
        "// GENERATED by tool/gen_firebase_options.py - do not edit by hand.\n\n"
        "import 'package:firebase_core/firebase_core.dart';\n\n"
        "class FirebaseConfig {\n"
        "  static const bool configured = true;\n"
        "  static const FirebaseOptions? android = FirebaseOptions(\n"
        f"{fields}\n"
        "  );\n"
        "}\n",
        encoding="utf-8",
    )
    print(f"Firebase configured for project '{options['projectId']}' -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
